#!/bin/bash
#
# User Data for the WordPress master web server: runs once, as root, on first boot.
# Installs Apache, PHP and WordPress, and connects WordPress to the database.
#
# The __PLACEHOLDERS__ are replaced by web_master.py before launch,
# so no real values are stored in this file.

DB_HOST="__DB_HOST__"
DB_NAME="__DB_NAME__"
DB_USER="__DB_USER__"
DB_PASSWORD="__DB_PASSWORD__"

# --- Swap: a t2.nano has only 512 MB of RAM ---
dd if=/dev/zero of=/swapfile bs=1M count=1024
chmod 600 /swapfile
mkswap /swapfile
swapon /swapfile
echo "/swapfile swap swap defaults 0 0" >> /etc/fstab

# --- OS updates, Apache, PHP, and the MariaDB client (for testing the connection) ---
dnf update -y
dnf install -y httpd php php-fpm php-mysqlnd php-gd php-mbstring php-xml mariadb105

# --- WordPress files into Apache's web root ---
cd /tmp
curl -sO https://wordpress.org/latest.tar.gz
tar xzf latest.tar.gz
cp -r wordpress/* /var/www/html/

# --- wp-config.php: WordPress's settings file ---
# Unique secret keys for login cookies, generated by WordPress's own service
SALTS=$(curl -s https://api.wordpress.org/secret-key/1.1/salt/)

# \$ keeps a literal $ for PHP; plain ${...} is filled in by bash now
cat > /var/www/html/wp-config.php <<EOF
<?php
define('DB_NAME', '${DB_NAME}');
define('DB_USER', '${DB_USER}');
define('DB_PASSWORD', '${DB_PASSWORD}');
define('DB_HOST', '${DB_HOST}');
define('DB_CHARSET', 'utf8mb4');
define('DB_COLLATE', '');

${SALTS}

\$table_prefix = 'wp_';

// Build the site address from the request, so the same files work when the
// site is reached by this instance's IP now and by the load balancer later
\$host = isset(\$_SERVER['HTTP_HOST']) ? \$_SERVER['HTTP_HOST'] : 'localhost';
define('WP_HOME', 'http://' . \$host);
define('WP_SITEURL', 'http://' . \$host);

define('WP_DEBUG', false);
if (!defined('ABSPATH')) {
    define('ABSPATH', __DIR__ . '/');
}
require_once ABSPATH . 'wp-settings.php';
EOF

# --- Instance info page (content inserted by web_master.py from instance-info.php) ---
# Quoted 'PHP' marker: bash copies the content exactly, without expanding anything
cat > /var/www/html/instance-info.php <<'PHP'
__INSTANCE_INFO_PHP__
PHP

# --- Custom CloudWatch metrics (content inserted by web_master.py from metrics.sh) ---
cat > /usr/local/bin/a2-metrics.sh <<'METRICS'
__METRICS_SH__
METRICS
chmod 755 /usr/local/bin/a2-metrics.sh

# A systemd service that runs the script once...
cat > /etc/systemd/system/a2-metrics.service <<EOF
[Unit]
Description=Push custom memory and swap metrics to CloudWatch

[Service]
Type=oneshot
ExecStart=/usr/local/bin/a2-metrics.sh
EOF

# ...and a timer that starts it every minute, beginning 1 minute after boot
cat > /etc/systemd/system/a2-metrics.timer <<EOF
[Unit]
Description=Run a2-metrics every minute

[Timer]
OnBootSec=1min
OnUnitActiveSec=1min

[Install]
WantedBy=timers.target
EOF

systemctl daemon-reload
systemctl enable --now a2-metrics.timer


# --- Apache serves the files, so it must own them ---
chown -R apache:apache /var/www/html

# --- Start PHP and Apache now and at every boot ---
systemctl enable --now php-fpm
systemctl enable --now httpd